#!/usr/bin/env python
"""Prepare the images used by the PDBrain-LM website.

Reads the figures produced in the visualization folder and writes web-ready
copies into ``assets/img``:

* rotation GIFs are copied unchanged, and their first frame is saved as a
  still (shown while the GIF loads, and when motion is paused);
* section MIPs (PNG) are re-encoded as *lossless* WebP - same pixels, about
  half the size. Lossy encoding is avoided on purpose: chroma subsampling
  visibly desaturates the small magenta pS129 puncta;
* ``assets/js/media-manifest.js`` is rewritten with the pixel size of every
  image, so the page can reserve space and keep both animals at one scale.

Usage (from the repository root)::

    python tools/prepare_media.py --viz ../visualization_PDBrain-LM_v2

Requires Pillow (``pip install pillow``). Nothing in the source folder is
modified.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parent.parent
IMG = REPO / "assets" / "img"

# group key -> (animal id, sub-folder of the visualization root)
GROUPS = {
    "pff": ("CR2343", "whole_brain"),
    "monomer": ("CR2337", "monomer_CR2337/whole_brain"),
}
PLANES = ("coronal", "sagittal", "horizontal")
LEVELS = (1, 2, 3)
# channel key used on the site -> suffix used in the source file names
CHANNELS = {"af": "autofl", "th": "TH", "ps129": "pS129"}
# rotation variants: site name -> source suffix
ROTATIONS = {"4panel": "rotation_4panel_horizontal", "merge": "rotation_merge"}


def save_lossless_webp(im: Image.Image, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.convert("RGB").save(dst, "WEBP", lossless=True, method=6)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--viz",
        type=Path,
        default=REPO.parent / "visualization_PDBrain-LM_v2",
        help="folder holding whole_brain/ and monomer_CR2337/ (default: %(default)s)",
    )
    args = ap.parse_args()
    viz: Path = args.viz
    if not viz.is_dir():
        print(f"error: visualization folder not found: {viz}", file=sys.stderr)
        return 1

    manifest: dict = {"rotation": {}, "sections": {}}
    total_in = total_out = 0

    for group, (animal, sub) in GROUPS.items():
        src_dir = viz / sub

        # --- rotation GIFs + stills -------------------------------------
        manifest["rotation"][group] = {}
        for name, suffix in ROTATIONS.items():
            src = src_dir / f"{animal}_v2_{suffix}.gif"
            dst = IMG / "rotation" / f"{group}-{name}.gif"
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)
            with Image.open(src) as gif:
                frames = getattr(gif, "n_frames", 1)
                duration = gif.info.get("duration", 0)
                gif.seek(0)
                still = gif.convert("RGB")
            save_lossless_webp(still, dst.with_name(f"{group}-{name}-still.webp"))
            manifest["rotation"][group][name] = {
                "w": still.width,
                "h": still.height,
                "frames": frames,
                "frameMs": duration,
            }
            total_in += src.stat().st_size
            total_out += dst.stat().st_size

        # --- section MIPs ------------------------------------------------
        manifest["sections"][group] = {}
        for plane in PLANES:
            sizes = set()
            for level in LEVELS:
                for key, suffix in CHANNELS.items():
                    src = src_dir / f"{animal}_v2_MIP_{plane}_{level}_{suffix}.png"
                    dst = IMG / "sections" / group / f"{plane}-{level}-{key}.webp"
                    with Image.open(src) as im:
                        sizes.add(im.size)
                        save_lossless_webp(im, dst)
                    total_in += src.stat().st_size
                    total_out += dst.stat().st_size
            if len(sizes) != 1:
                print(f"warning: {group}/{plane} images differ in size: {sizes}")
            w, h = sorted(sizes)[0]
            manifest["sections"][group][plane] = {"w": w, "h": h}

    out = REPO / "assets" / "js" / "media-manifest.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "/* Generated by tools/prepare_media.py - do not edit by hand. */\n"
        "window.PDB_MEDIA = " + json.dumps(manifest, indent=2) + ";\n",
        encoding="utf-8",
    )

    print(f"source  {total_in / 1e6:6.1f} MB")
    print(f"written {total_out / 1e6:6.1f} MB  -> {IMG}")
    print(f"manifest -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
